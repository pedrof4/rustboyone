def main():
    destination = Path.cwd() / "dmg-emu"
    try:
        destination.mkdir()
    except FileExistsError:
        print(f"Já existe um arquivo ou diretório em {destination}.", file=sys.stderr)
        return 1

    files = json.loads(zlib.decompress(base64.b85decode(PAYLOAD)))
    for name, content in files.items():
        path = destination / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8"))
    extractor = Path(__file__).resolve()
    (destination / extractor.name).write_bytes(extractor.read_bytes())
    print(f"Projeto recriado em {destination}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
